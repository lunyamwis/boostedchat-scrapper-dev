# Define the GPT Block (Transformer Block)
class GPTBlock(nn.Module):
    def __init__(self, embedding_dim, n_heads):
        super(GPTBlock, self).__init__()
        self.attention = nn.MultiheadAttention(embedding_dim, n_heads)
        self.ln1 = nn.LayerNorm(embedding_dim)
        self.feed_forward = nn.Sequential(
            nn.Linear(embedding_dim, 4 * embedding_dim),
            nn.ReLU(),
            nn.Linear(4 * embedding_dim, embedding_dim)
        )
        self.ln2 = nn.LayerNorm(embedding_dim)

    def forward(self, x):
        attn_output, _ = self.attention(x, x, x)
        x = self.ln1(x + attn_output)  # Residual connection
        ff_output = self.feed_forward(x)
        return self.ln2(x + ff_output)  # Residual connection

# Define the Simple GPT Model
class SimpleGPT(nn.Module):
    def __init__(self, num_blocks, embedding_dim, n_heads):
        super(SimpleGPT, self).__init__()
        self.embedding = nn.Embedding(256, embedding_dim)  # Simple embedding layer for characters
        self.blocks = nn.ModuleList([GPTBlock(embedding_dim, n_heads) for _ in range(num_blocks)])
        self.fc_out = nn.Linear(embedding_dim, 256)  # Output layer for character probabilities

    def forward(self, x):
        x = self.embedding(x)  # Embed input
        for block in self.blocks:
            x = block(x)
        return self.fc_out(x)

