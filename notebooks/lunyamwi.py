# Define the VAE model
class VAE(Model):
    def __init__(self, input_dim, hidden_dim, latent_dim):
        super(VAE, self).__init__()
        # Encoder
        self.encoder = tf.keras.Sequential([
            layers.Dense(hidden_dim, activation='relu'),  # Hidden layer
            layers.Dense(latent_dim + latent_dim),  # Mean and log variance of latent space
        ])

        # Decoder
        self.decoder = tf.keras.Sequential([
            layers.Dense(hidden_dim, activation='relu'),  # Hidden layer
            layers.Dense(input_dim, activation='sigmoid'),  # Output layer
        ])

    def encode(self, x):
        mean, logvar = tf.split(self.encoder(x), num_or_size_splits=2, axis=1)
        return mean, logvar

    def reparameterize(self, mean, logvar):
        epsilon = tf.random.normal(shape=mean.shape)
        return mean + tf.exp(0.5 * logvar) * epsilon

    def decode(self, z):
        return self.decoder(z)

    def call(self, x):
        mean, logvar = self.encode(x)
        z = self.reparameterize(mean, logvar)
        reconstructed = self.decode(z)
        return reconstructed, mean, logvar

# Loss function for VAE
def loss_function(model, x, reconstructed, mean, logvar):
    # Reconstruction loss
    reconstruction_loss = tf.reduce_mean(
        tf.keras.losses.binary_crossentropy(x, reconstructed)
    )
    # KL divergence loss
    kl_loss = -0.5 * tf.reduce_mean(1 + logvar - tf.square(mean) - tf.exp(logvar))
    total_loss = reconstruction_loss + kl_loss
    return total_loss

