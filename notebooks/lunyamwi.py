# Define the RNN model
class RNNModel(nn.Module):
    def __init__(self, vocab_size, embedding_dim, hidden_size, output_size, num_layers=1):
        super(RNNModel, self).__init__()
        self.embedding = nn.Embedding(vocab_size, embedding_dim)  # Embedding layer
        self.rnn = nn.RNN(embedding_dim, hidden_size, num_layers, batch_first=True)  # RNN layer
        self.fc = nn.Linear(hidden_size, output_size)  # Fully connected layer

    def forward(self, x):
        x = self.embedding(x)  # Convert indices to embeddings
        out, _ = self.rnn(x)  # Forward propagate RNN
        out = out[:, -1, :]  # Get the last time step's output
        out = self.fc(out)  # Pass through the fully connected layer
        return out

